async function run() {
    console.log('Transforming and inserting ' + data.length + ' records into the primary inventory table...');
    const records = data.map(item => {
        const id = crypto.randomUUID();
        const now = new Date().toISOString();
        // Build JSON `data` payload exactly matching the system's UseInventory structure
        const payload = {
            id,
            nombre: item.nombre,
            categoria: item.categoria,
            cantidad: item.stock,
            estado: 'Disponible',
            ubicacion: 'Bodega Principal',
            fechaAdquisicion: now.split('T')[0],
            historialUso: [],
            notas: (item.descripcion ? item.descripcion + ' | ' : '') + 'Filtro original: ' + item.filtro,
        };

        return {
            id,
            data: payload,
            created_at: now,
            updated_at: now
        };
    });

    const chunkSize = 50;
    for (let i = 0; i < records.length; i += chunkSize) {
        const chunk = records.slice(i, i + chunkSize);
        const { error } = await supabase.from('inventory').insert(chunk);
        if (error) {
            console.error('Error inserting chunk ' + i + ':', error);
        } else {
            console.log('Successfully inserted items ' + i + ' to ' + (Math.min(i + chunkSize, records.length) - 1));
        }
    }
}

run();
